#!/usr/bin/env bash
# Sync the TDD Admin profile view with the latest asjain-bit/M42-Tech-Due-Dilligence code.
#
# Usage: pnpm sync:tdd-admin [branch]   (default branch: main)
#
# Replaces src/tdd-admin/components, contexts and tdd-admin.css with the source repo's code,
# rewrites imports to the isolated @/tdd-admin/* paths, drops the source login screen,
# prefixes story titles with "TDD Admin/", then formats, typechecks and tests.
# TddAdminApp.tsx is kept: it mirrors the source src/app/page.tsx without the login, and the
# script tells you when that page changed so you can carry the change over by hand.
# Nothing is committed or pushed.

set -euo pipefail

SOURCE_REPO="https://github.com/asjain-bit/M42-Tech-Due-Dilligence.git"
BRANCH="${1:-main}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TARGET="$ROOT/src/tdd-admin"
COMMIT_FILE="$TARGET/SOURCE_COMMIT"

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

echo "→ Fetching $SOURCE_REPO ($BRANCH)"
git clone -q --depth 50 --branch "$BRANCH" "$SOURCE_REPO" "$WORK/src-repo"
SRC="$WORK/src-repo/src"
NEW_COMMIT="$(git -C "$WORK/src-repo" rev-parse HEAD)"
OLD_COMMIT="$(cat "$COMMIT_FILE" 2>/dev/null || true)"

if [[ "$NEW_COMMIT" == "$OLD_COMMIT" ]]; then
  echo "✓ Already up to date with ${NEW_COMMIT:0:7}"
  exit 0
fi

echo "→ Copying components and contexts"
rm -rf "$TARGET/components" "$TARGET/contexts"
cp -R "$SRC/components" "$TARGET/components"
mkdir -p "$TARGET/contexts"
cp -R "$SRC/contexts/." "$TARGET/contexts/"
# The shared TDD Phase 2 login is used instead
rm -f "$TARGET/components/screens/LoginScreen".*

echo "→ Rewriting imports and story titles"
grep -rlE "@/(components|contexts)/" "$TARGET/components" "$TARGET/contexts" | while read -r f; do
  sed -i.bak -e "s#@/components/#@/tdd-admin/components/#g" -e "s#@/contexts/#@/tdd-admin/contexts/#g" "$f"
done
grep -rlE "title: '(Atoms|Molecules|Organisms|Templates|Screens)/" "$TARGET/components" | while read -r f; do
  sed -i.bak -E "s#^([[:space:]]*title: ')(Atoms|Molecules|Organisms|Templates|Screens)/#\1TDD Admin/\2/#" "$f"
done
find "$TARGET" -name '*.bak' -delete

echo "→ Rebuilding scoped styles"
{
  cat <<'EOF'
/*
 * TDD Admin profile view — styles carried over from the M42 Tech Due Diligence repo.
 * Every rule is scoped to `.tdd-admin` so no other profile view is affected.
 * Generated by scripts/sync-tdd-admin.sh — do not edit by hand.
 */

/* Source design tokens (primitives, light theme and brand), scoped to the TDD Admin view */
EOF
  for f in primitives light; do
    sed -n '/{/,/^}/p' "$SRC/styles/tokens/$f.css" | sed -E 's#^(:root|\[data-theme="light"\]|\[data-theme='"'"'light'"'"'\]) \{#.tdd-admin {#'
    echo
  done
  sed -n '/^:root {/,/^}/p' "$SRC/styles/tokens/brand.css" | sed -E 's#^:root \{#.tdd-admin {#'
  cat <<'EOF'

/* Source font weight scale (bold = 600, extrabold = 700, black = 800) */
.tdd-admin {
  --font-weight-black: 800;
  --font-weight-extrabold: 700;
  --font-weight-bold: 600;
  font-family: var(--font-sans, 'Poppins', system-ui, sans-serif);
}

EOF
  sed -n '/^\/\* Subtle custom horizontal scrollbar/,$p' "$SRC/app/globals.css" |
    sed -E 's#^(\.subtle-scrollbar)#.tdd-admin \1#; s#^(input|textarea|select)#.tdd-admin \1#'
} >"$TARGET/tdd-admin.css"

echo "$NEW_COMMIT" >"$COMMIT_FILE"

echo "→ Formatting"
cd "$ROOT"
pnpm -s exec prettier --write --log-level warn "src/tdd-admin"

if [[ -n "$OLD_COMMIT" ]] && git -C "$WORK/src-repo" cat-file -e "$OLD_COMMIT" 2>/dev/null; then
  if ! git -C "$WORK/src-repo" diff --quiet "$OLD_COMMIT" "$NEW_COMMIT" -- src/app/page.tsx; then
    echo
    echo "⚠ The source src/app/page.tsx changed (new pages or tabs?). Carry it over into"
    echo "  src/tdd-admin/TddAdminApp.tsx:"
    git -C "$WORK/src-repo" --no-pager diff "$OLD_COMMIT" "$NEW_COMMIT" -- src/app/page.tsx
  fi
  if ! git -C "$WORK/src-repo" diff --quiet "$OLD_COMMIT" "$NEW_COMMIT" -- package.json; then
    echo
    echo "⚠ The source package.json changed. Check for new dependencies:"
    git -C "$WORK/src-repo" --no-pager diff "$OLD_COMMIT" "$NEW_COMMIT" -- package.json
  fi
fi

echo
echo "→ Typecheck and tests"
pnpm -s typecheck
pnpm -s test >/dev/null && echo "✓ Tests pass"

echo
echo "✓ Synced TDD Admin to ${NEW_COMMIT:0:7}${OLD_COMMIT:+ (was ${OLD_COMMIT:0:7})}. Review with: git diff --stat src/tdd-admin"
echo "  Then commit and push to deploy."
